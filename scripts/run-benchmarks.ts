import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import {
  BASELINE_OPTIMIZER_VERSION,
  RECUT_OPTIMIZER_VERSION,
  evaluateOptimization,
  parseWorkshopFixture,
  verifyPlan,
} from '@/lib/optimizer';
import { formatMinorCurrency } from '@/lib/utils';

const rootDir = process.cwd();
const sampleRaw = JSON.parse(
  readFileSync(path.join(rootDir, 'fixtures/sample-workshop.json'), 'utf8')
);
const suiteRaw = JSON.parse(
  readFileSync(path.join(rootDir, 'fixtures/benchmark-suite.json'), 'utf8')
) as unknown[];

const allFixtures = [sampleRaw, ...suiteRaw].map((f) => parseWorkshopFixture(f));

interface BenchmarkRow {
  fixtureId: string;
  title: string;
  inputHash: string;
  seed: number;
  status: string;
  baselineNewSheets: number;
  recutNewSheets: number;
  baselineCost: string;
  recutCost: string;
  costDelta: string;
  reductionPct: string;
  remnantsUsed: number;
  baselineTrueWasteMm2: number;
  recutTrueWasteMm2: number;
  verifierPassed: boolean;
  durationMs: number;
}

const rows: BenchmarkRow[] = [];

for (const fx of allFixtures) {
  const evalStart = performance.now();
  const result = evaluateOptimization(fx.problem);
  const totalDurationMs = Math.round(performance.now() - evalStart);

  let verifierPassed = true;
  if (result.baseline.status === 'feasible') {
    verifierPassed =
      verifierPassed &&
      verifyPlan(fx.problem, result.baseline, { baselineNewSheetsOnly: true })
        .valid;
  }
  if (result.optimized.status === 'feasible') {
    verifierPassed =
      verifierPassed && verifyPlan(fx.problem, result.optimized).valid;
  }

  const currency = result.currencyCode;
  rows.push({
    fixtureId: fx.fixtureId,
    title: fx.title,
    inputHash: result.inputHash,
    seed: fx.problem.seed ?? 42,
    status: result.optimized.status,
    baselineNewSheets: result.baseline.metrics.newSheetCount,
    recutNewSheets: result.optimized.metrics.newSheetCount,
    baselineCost: formatMinorCurrency(
      result.baseline.metrics.newSheetPurchaseCostMinor,
      currency
    ),
    recutCost: formatMinorCurrency(
      result.optimized.metrics.newSheetPurchaseCostMinor,
      currency
    ),
    costDelta: result.comparison
      ? formatMinorCurrency(result.comparison.costDeltaMinor, currency)
      : 'N/A',
    reductionPct:
      result.comparison && result.comparison.purchaseReductionPct !== null
        ? `${result.comparison.purchaseReductionPct.toFixed(1)}%`
        : 'N/A',
    remnantsUsed: result.optimized.metrics.availableRemnantUnitsUsed,
    baselineTrueWasteMm2:
      result.baseline.metrics.unusableScrapAreaMm2 +
      result.baseline.metrics.kerfLossAreaMm2,
    recutTrueWasteMm2:
      result.optimized.metrics.unusableScrapAreaMm2 +
      result.optimized.metrics.kerfLossAreaMm2,
    verifierPassed,
    durationMs: totalDurationMs,
  });
}

const sampleEval = evaluateOptimization(allFixtures[0]!.problem);

const markdown = `# ReCut OS — Reproducible Benchmark Report

> **Generated by:** \`npm run benchmark\` (\`scripts/run-benchmarks.ts\`)  
> **Observed at (UTC):** ${new Date().toISOString()}  
> **Runtime environment:** Node ${process.version} on ${os.platform()} ${os.arch()} (${os.cpus()[0]?.model?.trim() ?? 'CPU'})  
> **Baseline version:** \`${BASELINE_OPTIMIZER_VERSION}\`  
> **Optimizer version:** \`${RECUT_OPTIMIZER_VERSION}\`

## Methodology & Honest Accounting Caveats

1. **Identical manufacturing constraints:** Both the baseline and ReCut OS enforce the exact same expanded part list, integer dimensions (\`mm\`), saw kerf subtraction (\`kerfMm\`), grain axis alignment, and part rotation permissions.
2. **Independent cut-tree verification:** Every feasible plan (both baseline and ReCut OS) is replayed from root stock dimensions by \`verifyPlan\` (\`lib/optimizer/verify.ts\`), checking edge-to-edge guillotine splits, kerf strip geometry, non-overlap, part bijection, and exact \`1 mm²\` area conservation.
3. **Purchase spend vs physical waste:** \`Cost Delta\` compares **modeled new-sheet purchase spend** against a deterministic new-sheet-only First-Fit Decreasing (FFD) guillotine baseline. Existing remnants have sunk acquisition cost (\`0\` new purchase spend), and consuming them draws down workshop offcut inventory.
4. **No fabricated claims:** Scenarios with empty inventory or unusable offcuts honestly report \`0%\` purchase reduction. None of these fixtures represent customer pilot deployments or verified emissions reductions.

---

## Summary Across Deterministic Fixtures

| Fixture ID | Input Hash | Seed | Status | Baseline New Sheets | ReCut New Sheets | Baseline Spend | ReCut Spend | Modeled Spend Delta | Purchase Reduction | Remnants Used | Verifier | Run Time |
|---|---|---:|---|---:|---:|---:|---:|---:|---:|---:|:---:|---:|
${rows
  .map(
    (r) =>
      `| \`${r.fixtureId}\` | \`${r.inputHash}\` | ${r.seed} | \`${r.status}\` | ${r.baselineNewSheets} | ${r.recutNewSheets} | ${r.baselineCost} | ${r.recutCost} | ${r.costDelta} | ${r.reductionPct} | ${r.remnantsUsed} | ${r.verifierPassed ? 'PASS' : 'FAIL'} | ${r.durationMs} ms |`
  )
  .join('\n')}

---

## Detailed Accounting: \`sample-workshop-v1\` (Public Demo Fixture)

- **Input hash:** \`${sampleEval.inputHash}\` (Seed \`${sampleEval.optimized.seed}\`)
- **Demand:** 10 expanded parts across 4 cabinet part SKUs (\`${sampleEval.optimized.metrics.partAreaMm2.toLocaleString('en-US')} mm²\` required part area)
- **Baseline (\`${sampleEval.baseline.algorithmVersion}\`):**
  - New standard sheets purchased: **${sampleEval.baseline.metrics.newSheetCount}** (${formatMinorCurrency(sampleEval.baseline.metrics.newSheetPurchaseCostMinor, sampleEval.currencyCode)})
  - Opened stock area: \`${sampleEval.baseline.metrics.openedStockAreaMm2.toLocaleString('en-US')} mm²\`
  - Recoverable residual area: \`${sampleEval.baseline.metrics.recoverableRemnantAreaMm2.toLocaleString('en-US')} mm²\` (${sampleEval.baseline.metrics.recoverableRemnantCount} qualifying regions)
  - Unusable scrap area: \`${sampleEval.baseline.metrics.unusableScrapAreaMm2.toLocaleString('en-US')} mm²\`
  - Saw kerf loss area: \`${sampleEval.baseline.metrics.kerfLossAreaMm2.toLocaleString('en-US')} mm²\` (${sampleEval.baseline.metrics.totalCutCount} guillotine cuts)
- **ReCut OS (\`${sampleEval.optimized.algorithmVersion}\`):**
  - New standard sheets purchased: **${sampleEval.optimized.metrics.newSheetCount}** (${formatMinorCurrency(sampleEval.optimized.metrics.newSheetPurchaseCostMinor, sampleEval.currencyCode)})
  - Owned remnants consumed: **${sampleEval.optimized.metrics.availableRemnantUnitsUsed}** (\`${sampleEval.optimized.metrics.availableRemnantAreaUsedMm2.toLocaleString('en-US')} mm²\`)
  - Opened stock area: \`${sampleEval.optimized.metrics.openedStockAreaMm2.toLocaleString('en-US')} mm²\`
  - Recoverable residual area (pending confirmation): \`${sampleEval.optimized.metrics.recoverableRemnantAreaMm2.toLocaleString('en-US')} mm²\` (${sampleEval.optimized.metrics.recoverableRemnantCount} qualifying regions)
  - Unusable scrap area: \`${sampleEval.optimized.metrics.unusableScrapAreaMm2.toLocaleString('en-US')} mm²\`
  - Saw kerf loss area: \`${sampleEval.optimized.metrics.kerfLossAreaMm2.toLocaleString('en-US')} mm²\` (${sampleEval.optimized.metrics.totalCutCount} guillotine cuts)
`;

mkdirSync(path.join(rootDir, 'docs'), { recursive: true });
writeFileSync(path.join(rootDir, 'docs/benchmarks.md'), markdown, 'utf8');
console.log('Wrote docs/benchmarks.md successfully.\n');
for (const r of rows) {
  console.log(
    `${r.fixtureId.padEnd(30)} | status=${r.status.padEnd(10)} | baseline=${r.baselineNewSheets} (${r.baselineCost}) | recut=${r.recutNewSheets} (${r.recutCost}) | remnants=${r.remnantsUsed} | verifier=${r.verifierPassed}`
  );
}

describe('Benchmark suite execution', () => {
  it('verifies all feasible fixtures and writes docs/benchmarks.md', () => {
    expect(rows.every((r) => r.verifierPassed)).toBe(true);
  });
});
